"""Local eBay preparation and conservative Trading API payload construction."""
from __future__ import annotations

import html
from dataclasses import dataclass
from decimal import Decimal
from gettext import gettext as _
from pathlib import Path
from typing import TYPE_CHECKING, Final
from xml.etree import ElementTree as ET  # noqa: S405 - creates XML only

from kleinanzeigen_bot.ad_loading import resolve_ad_images
from kleinanzeigen_bot.ebay_api import child
from kleinanzeigen_bot.ebay_description import sanitize_description
from kleinanzeigen_bot.model.ebay_model import EbayListing

if TYPE_CHECKING:
    from kleinanzeigen_bot.model.ad_model import Ad
    from kleinanzeigen_bot.model.config_model import AdDefaults
    from kleinanzeigen_bot.model.ebay_model import EbayConfig


MAX_PICTURES:Final = 24


@dataclass(frozen = True)
class PreparedListing:
    title:str
    description:str
    removed_links:int
    pictures:list[Path]
    settings:EbayListing
    price:Decimal | None
    missing:list[str]

    @property
    def auction(self) -> bool:
        return self.settings.listing_format == "auction"


def prepare(ad:Ad, path:Path, defaults:AdDefaults, config:EbayConfig) -> PreparedListing:
    settings = config.defaults.model_dump()
    if ad.ebay is not None:
        settings.update(ad.ebay.model_dump(exclude_unset = True))
    listing = EbayListing.model_validate(settings)
    prefix = ad.description_prefix if ad.description_prefix is not None else defaults.description_prefix or ""
    suffix = ad.description_suffix if ad.description_suffix is not None else defaults.description_suffix or ""
    description, removed = sanitize_description(prefix + ad.description + suffix)
    missing = [
        "ebay." + field
        for field in ("category_id", "condition_id", "shipping_profile_id", "return_profile_id", "payment_profile_id", "postal_code")
        if not getattr(listing, field)
    ]
    price = listing.price if listing.price is not None else Decimal(ad.price) if ad.price is not None else None
    if listing.listing_format == "auction":
        price = listing.auction_start_price
        if price is None:
            missing.append("ebay.auction_start_price")
        if listing.auction_duration is None:
            missing.append("ebay.auction_duration")
        if listing.quantity != 1 or listing.best_offer:
            missing.append(_("auctions require quantity one and Best Offer disabled"))
    elif price is None or price <= 0:
        missing.append(_("a positive eBay price"))
    if (ad.type == "WANTED" or ad.price_type in {"GIVE_AWAY", "NOT_APPLICABLE"} or ad.price is None or ad.price <= 0):
        override = listing.auction_start_price if listing.listing_format == "auction" else listing.price
        if override is None:
            missing.append(_("an explicit eBay price override for wanted, giveaway or unpriced sources"))
    pictures = [Path(image) for image in resolve_ad_images(str(path), ad.images)] if ad.images else []
    if not pictures:
        missing.append(_("at least one local picture"))
    if len(pictures) > MAX_PICTURES:
        missing.append(_("at most 24 pictures"))
    if not description.strip():
        missing.append(_("a description after link removal"))
    return PreparedListing(ad.title, description, removed, pictures, listing, price, missing)


def build_item(prepared:PreparedListing, config:EbayConfig, source_id:str, listing_uuid:str, picture_urls:list[str]) -> ET.Element:
    if prepared.missing or prepared.price is None:
        raise ValueError(_("Complete the missing eBay details before verification or publication"))
    settings = prepared.settings
    item = ET.Element("Item")
    child(item, "Title", prepared.title)
    # eBay interprets descriptions as HTML. Escape every remaining character,
    # then add only paragraph breaks generated by us.
    child(item, "Description", "<p>" + html.escape(prepared.description).replace("\n", "<br>") + "</p>")
    child(child(item, "PrimaryCategory"), "CategoryID", settings.category_id)
    child(item, "CategoryMappingAllowed", "false")
    child(item, "ConditionID", settings.condition_id)
    child(item, "Country", settings.country)
    child(item, "Currency", config.currency)
    child(item, "PostalCode", settings.postal_code)
    child(item, "ListingType", "Chinese" if prepared.auction else "FixedPriceItem")
    child(item, "ListingDuration", settings.auction_duration if prepared.auction else "GTC")
    child(item, "StartPrice", prepared.price).set("currencyID", config.currency)
    child(item, "Quantity", settings.quantity)
    child(item, "UUID", listing_uuid)
    child(item, "ApplicationData", source_id)
    child(item, "SKU", source_id)
    if not prepared.auction:
        child(child(item, "BestOfferDetails"), "BestOfferEnabled", str(settings.best_offer).lower())
    profiles = child(item, "SellerProfiles")
    for container, name, value in (
        ("SellerShippingProfile", "ShippingProfileID", settings.shipping_profile_id),
        ("SellerReturnProfile", "ReturnProfileID", settings.return_profile_id),
        ("SellerPaymentProfile", "PaymentProfileID", settings.payment_profile_id),
    ):
        child(child(profiles, container), name, value)
    specifics = child(item, "ItemSpecifics")
    for name, values in settings.aspects.items():
        entry = child(specifics, "NameValueList")
        child(entry, "Name", name)
        for value in values:
            child(entry, "Value", value)
    pictures = child(item, "PictureDetails")
    for url in picture_urls:
        child(pictures, "PictureURL", url)
    return item
